// codexBase is the tail of a merged Codex config: what precedes the rea table.
const codexBase = "# Codex configuration (auto-generated by Autopus-ADK)\n" +
	"approval_policy = \"on-request\"\n" +
	"\n" +
	"[mcp_servers.context7]\n" +
	"command = \"npx\"\n" +
	"args = [\"-y\", \"@upstash/context7-mcp@latest\"]\n"

// codexX1 is the literal managed table of the MCP Entry Shape Contract.
const codexX1 = "[mcp_servers.rea]\n" +
	"command = \"npx\"\n" +
	codexX1Args + "\n" +
	"startup_timeout_sec = 120\n"

const codexX1Args = "args = [\"-y\", \"--prefix=/\", \"rea-agents@6.5.0\", \"mcp\"]"

// codexX8 is the table v0.50.127 wrote, which ran npx without --prefix=/.
var codexX8 = strings.Replace(codexX1, codexX1Args, "args = [\"-y\", \"rea-agents@6.5.0\", \"mcp\"]", 1)

func TestClassifyCodexTOML_S4Rows(t *testing.T) {
	cases := []struct {
		id    string
		table string
		want  Class
	}{
		{"X1", codexX1, ClassManaged},
		{"X2", strings.Replace(codexX1, "startup_timeout_sec = 120\n", "", 1), ClassUserOwned},
		{"X3", codexX1 + "tool_timeout_sec = 120\n", ClassUserOwned},
		{"X4", strings.Replace(codexX1, "\ncommand", "\n# mine\ncommand", 1), ClassUserOwned},
		{"X5", strings.Replace(codexX1, "6.5.0", "6.4.0", 1), ClassOtherPin},
		{"X6", strings.Replace(codexX1, "[mcp_servers.rea]", "[mcp_servers.rea-agents]", 1), ClassAbsent},
		{"X7", codexX1 + "\n[mcp_servers.rea.env]\nA = \"1\"\n", ClassUserOwned},
		{"X8", codexX8, ClassManaged},
		{"X9", strings.Replace(codexX8, "6.5.0", "6.4.0", 1), ClassOtherPin},
		{"another prefix", strings.Replace(codexX1, "--prefix=/", "--prefix=/tmp", 1), ClassUserOwned},
		{"blank lines inside", "[mcp_servers.rea]\n\ncommand = \"npx\"\n\n" + codexX1Args + "\nstartup_timeout_sec = 120\n", ClassManaged},
		{"header comment", strings.Replace(codexX1, "[mcp_servers.rea]", "[mcp_servers.rea] # mine", 1), ClassUserOwned},
		{"quoted header", strings.Replace(codexX1, "[mcp_servers.rea]", "[mcp_servers.\"rea\"]", 1), ClassUserOwned},
		{"reordered", "[mcp_servers.rea]\n" + codexX1Args + "\ncommand = \"npx\"\nstartup_timeout_sec = 120\n", ClassUserOwned},
		{"subtable only", "[mcp_servers.rea.env]\nA = \"1\"\n", ClassUserOwned},
		{"array table", "[[mcp_servers.rea]]\ncommand = \"npx\"\n", ClassUserOwned},
		{"inline table", "[mcp_servers]\nrea = { command = \"npx\" }\n", ClassUserOwned},
		{"dotted key", "[mcp_servers]\nrea.command = \"npx\"\n", ClassUserOwned},
		{"dotted key of another table", "[mcp_servers.mine]\nrea.command = \"npx\"\n", ClassAbsent},
		{"duplicate table", codexX1 + "\n" + codexX1, ClassUserOwned},
		{"multi-line args", "[mcp_servers.rea]\ncommand = \"npx\"\nargs = [\n  \"-y\", \"--prefix=/\", \"rea-agents@6.5.0\", \"mcp\",\n]\nstartup_timeout_sec = 120\n", ClassUserOwned},
	}
	for _, tc := range cases {
		t.Run(tc.id, func(t *testing.T) {
			assert.Equal(t, tc.want, ClassifyCodexTOML(codexBase+"\n"+tc.table))
		})
	}
	assert.Equal(t, ClassAbsent, ClassifyCodexTOML(""))
	assert.Equal(t, ClassAbsent, ClassifyCodexTOML(codexBase))
	assert.Equal(t, ClassUserOwned, ClassifyCodexTOML("mcp_servers.rea.command = \"npx\"\n"+codexBase), "root dotted key")
}

func TestClassifyCodexTOML_IgnoresHeadersInsideMultilineStrings(t *testing.T) {
	for _, delimiter := range []string{`"""`, `'''`} {
		text := codexBase + "\n[mcp_servers.mine]\ncommand = \"mine\"\ndescription = " + delimiter + "\n" +
			codexX1 + delimiter + "\n"
		assert.Equal(t, ClassAbsent, ClassifyCodexTOML(text), delimiter)

		out, changed := ApplyCodexTOML(text, config.ReaMCPAdd)
		require.True(t, changed, delimiter)
		assert.Equal(t, text+"\n"+codexX1, out, delimiter)
		assert.Equal(t, ClassManaged, ClassifyCodexTOML(out), delimiter)
	}

	// A multiline string that starts inside the managed table makes the table's
	// body more than the three contract lines.
	text := codexBase + "\n[mcp_servers.rea]\ncommand = \"npx\"\nnote = \"\"\"\n[x]\n\"\"\"\n" +
		codexX1Args + "\nstartup_timeout_sec = 120\n"
	assert.Equal(t, ClassUserOwned, ClassifyCodexTOML(text))
}

func TestApplyCodexTOML_AddThenRemoveRestoresBytes(t *testing.T) {
	user := codexBase + "\n[mcp_servers.mine]\ncommand = \"mine-mcp\"  # keep\n"
	added, changed := ApplyCodexTOML(user, config.ReaMCPAdd)
	require.True(t, changed)
	assert.Equal(t, user+"\n"+codexX1, added, "one blank line, then the managed table at the end")

	again, changed := ApplyCodexTOML(added, config.ReaMCPAdd)
	assert.False(t, changed)
	assert.Equal(t, added, again)

	kept, changed := ApplyCodexTOML(added, config.ReaMCPKeep)
	assert.False(t, changed)
	assert.Equal(t, added, kept)

	removed, changed := ApplyCodexTOML(added, config.ReaMCPRemove)
	require.True(t, changed)
	assert.Equal(t, user, removed)

	_, changed = ApplyCodexTOML(user, config.ReaMCPRemove)
	assert.False(t, changed)
}

func TestApplyCodexTOML_RemoveKeepsSurroundingTablesByteIdentical(t *testing.T) {
	after := "[mcp_servers.mine]\ncommand = \"mine-mcp\"  # keep\n"
	middle := codexBase + "\n" + codexX1 + "\n" + after
	removed, changed := ApplyCodexTOML(middle, config.ReaMCPRemove)
	require.True(t, changed)
	assert.Equal(t, codexBase+"\n"+after, removed)

	// A comment block right before the next header belongs to that table.
	commented := codexBase + "\n" + codexX1 + "\n# my server\n" + after
	assert.Equal(t, ClassManaged, ClassifyCodexTOML(commented))
	removed, changed = ApplyCodexTOML(commented, config.ReaMCPRemove)
	require.True(t, changed)
	assert.Equal(t, codexBase+"\n# my server\n"+after, removed)

	// At the start of the file there is no blank line before the header, so the
	// one after the table goes instead.
	first := codexX1 + "\n" + after
	removed, changed = ApplyCodexTOML(first, config.ReaMCPRemove)
	require.True(t, changed)
	assert.Equal(t, after, removed)

	only, changed := ApplyCodexTOML(codexX1, config.ReaMCPRemove)
	require.True(t, changed)
	assert.Equal(t, "", only)
}

func TestApplyCodexTOML_LeavesUserOwnedAndOtherPinTablesByteIdentical(t *testing.T) {
	tables := map[string]string{
		"X2": strings.Replace(codexX1, "startup_timeout_sec = 120\n", "", 1),
		"X3": codexX1 + "tool_timeout_sec = 120\n",
		"X4": strings.Replace(codexX1, "\ncommand", "\n# mine\ncommand", 1),
		"X5": strings.Replace(codexX1, "6.5.0", "6.4.0", 1),
		"X7": codexX1 + "\n[mcp_servers.rea.env]\nA = \"1\"\n",
		"X9": strings.Replace(codexX8, "6.5.0", "6.4.0", 1),
	}
	for id, table := range tables {
		text := codexBase + "\n" + table
		for _, action := range []config.ReaMCPAction{config.ReaMCPAdd, config.ReaMCPRemove} {
			out, changed := ApplyCodexTOML(text, action)
			assert.False(t, changed, "%s %s", id, action)
			assert.Equal(t, text, out, "%s %s", id, action)
		}
	}

	// X6: rea-agents is another server; add appends rea and keeps it as is.
	x6 := codexBase + "\n" + strings.Replace(codexX1, "[mcp_servers.rea]", "[mcp_servers.rea-agents]", 1)
	out, changed := ApplyCodexTOML(x6, config.ReaMCPAdd)
	require.True(t, changed)
	assert.Equal(t, x6+"\n"+codexX1, out)
}

func TestApplyCodexTOML_EdgeTexts(t *testing.T) {
	out, changed := ApplyCodexTOML("", config.ReaMCPAdd)
	require.True(t, changed)
	assert.Equal(t, codexX1, out, "an empty file gets the table without a leading blank line")

	out, changed = ApplyCodexTOML("approval_policy = \"never\"", config.ReaMCPAdd)
	require.True(t, changed)
	assert.Equal(t, "approval_policy = \"never\"\n\n"+codexX1, out)

	_, changed = ApplyCodexTOML(codexBase, config.ReaMCPAction("bogus"))
	assert.False(t, changed)
}

func TestApplyCodexTOML_ReplacesOlderManagedPin(t *testing.T) {
	previous := ManagedPins
	ManagedPins = []string{"6.4.0", "6.5.0"}
	t.Cleanup(func() { ManagedPins = previous })

	after := "\n[mcp_servers.mine]\ncommand = \"mine-mcp\"\n"
	for _, table := range []string{codexX1, codexX8} {
		older := codexBase + "\n" + strings.Replace(table, "6.5.0", "6.4.0", 1) + after
		require.Equal(t, ClassManaged, ClassifyCodexTOML(older))
		out, changed := ApplyCodexTOML(older, config.ReaMCPAdd)
		require.True(t, changed)
		assert.Equal(t, codexBase+"\n"+codexX1+after, out)
	}
}

// X8, the v0.50.127 table, is Autopus-managed: add rewrites its args line in
// place and nothing else, and remove takes the table out as for X1.
func TestApplyCodexTOML_MovesTheRetiredTableToTheCurrentOne(t *testing.T) {
	after := "\n# my server\n[mcp_servers.mine]\ncommand = \"mine-mcp\"  # keep\n"
	retired := codexBase + "\n" + codexX8 + after
	require.Equal(t, ClassManaged, ClassifyCodexTOML(retired))

	added, changed := ApplyCodexTOML(retired, config.ReaMCPAdd)
	require.True(t, changed)
	assert.Equal(t, codexBase+"\n"+codexX1+after, added)
	_, changed = ApplyCodexTOML(added, config.ReaMCPAdd)
	assert.False(t, changed, "the current table is final")

	removed, changed := ApplyCodexTOML(retired, config.ReaMCPRemove)
	require.True(t, changed)
	assert.Equal(t, codexBase+after, removed)
	kept, changed := ApplyCodexTOML(retired, config.ReaMCPKeep)
	assert.False(t, changed)
	assert.Equal(t, retired, kept)
}
